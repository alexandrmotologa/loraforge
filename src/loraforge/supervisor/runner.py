    def run_training_job(
        self,
        config: FineTuningJobConfig,
        max_steps: Optional[int] = None,
    ) -> JobState:
        """Execute a bare-metal training subprocess and stream telemetry in real time."""
        job_id = config.job_id
        checkpoint_dir = str(self.work_dir / job_id / "checkpoints")

        # 1. Pre-flight predictive VRAM verification
        report = self.calculator.estimate(
            config.model,
            config.lora,
            config.quantization,
            config.training,
            config.gpu,
        )

        if report.status == "OOM":
            raise OOMRiskError(
                predicted_mb=report.peak_vram_mb,
                available_mb=config.gpu.total_vram_mb,
                safe_threshold_mb=config.gpu.usable_vram_mb,
                message=(
                    f"Training rejected: predicted peak VRAM ({report.peak_vram_mb:.1f} MB) "
                    f"exceeds hardware budget ({config.gpu.total_vram_mb} MB)."
                ),
            )

        worker_script = self.work_dir / job_id / "train_worker.py"
        self.generate_worker_script(config, worker_script)

        state = JobState(
            job_id=job_id,
            status=JobStatus.RUNNING,
            start_time=time.time(),
            total_steps=max_steps or (config.training.max_steps if config.training.max_steps > 0 else 50),
            output_checkpoint_dir=checkpoint_dir,
        )
        self._jobs[job_id] = state
        self._stop_flags[job_id] = False

        # 2. Launch training subprocess
        proc = subprocess.Popen(
            [sys.executable, str(worker_script)],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
            universal_newlines=True,
        )
        self._processes[job_id] = proc

        captured_output: List[str] = []

        try:
            for raw_line in proc.stdout:
                line = raw_line.strip()
                captured_output.append(line)

                # Cancellation check
                if self._stop_flags.get(job_id, False):
                    proc.terminate()
                    state.status = JobStatus.CANCELLED
                    state.end_time = time.time()
                    return state

                # Metric stream check
                if line.startswith("[METRIC]"):
                    try:
                        metric_data = json.loads(line[8:].strip())
                        metric = StepMetrics(
                            step=metric_data["step"],
                            epoch=metric_data.get("epoch", 0.0),
                            loss=metric_data["loss"],
                            learning_rate=metric_data.get("learning_rate", 0.0),
                            grad_norm=metric_data.get("grad_norm", 0.0),
                            vram_used_mb=metric_data.get("vram_used_mb", 0.0),
                            vram_peak_mb=metric_data.get("vram_used_mb", 0.0),
                            elapsed_seconds=round(time.time() - (state.start_time or time.time()), 2),
                        )
                        self.event_bus.record(metric)

                        # Memory watchdog tripwire verification
                        if metric.vram_used_mb > 0:
                            snap = GPUTelemetrySnapshot(
                                name=config.gpu.name,
                                vram_total_mb=float(config.gpu.total_vram_mb),
                                vram_used_mb=float(metric.vram_used_mb),
                                vram_free_mb=max(0.0, float(config.gpu.total_vram_mb - metric.vram_used_mb)),
                                vram_utilization_percent=(metric.vram_used_mb / config.gpu.total_vram_mb) * 100.0 if config.gpu.total_vram_mb > 0 else 0.0,
                            )
                            trip = self.watchdog.check(snap)
                            if trip.is_tripped:
                                proc.terminate()
                                state.status = JobStatus.OOM_ABORTED
                                state.error_message = f"MemoryWatchdog tripped: {trip.trip_reason}"
                                state.end_time = time.time()
                                return state

                        state.current_step = metric.step
                        state.current_epoch = metric.epoch
                        state.latest_loss = metric.loss
                        state.peak_vram_recorded_mb = max(state.peak_vram_recorded_mb, metric.vram_used_mb)

                    except json.JSONDecodeError:
                        pass

            proc.wait()
            state.end_time = time.time()

            if proc.returncode == 0:
                state.status = JobStatus.COMPLETED
            else:
                state.status = JobStatus.FAILED
                state.error_message = "\n".join(captured_output[-5:])

        except Exception as exc:
            proc.kill()
            state.status = JobStatus.FAILED
            state.error_message = str(exc)
            state.end_time = time.time()

        return state

    def run_dry_run_simulation(
        self,
        config: FineTuningJobConfig,
        total_steps: int = 50,
        step_delay: float = 0.02,
    ) -> JobState:
        """Run an in-process verified simulation of a training run for CI and dry-run testing."""
        job_id = config.job_id
        checkpoint_dir = str(self.work_dir / job_id / "checkpoints")

        # Run strict VRAM validation
        report = self.calculator.estimate(
            config.model,
            config.lora,
            config.quantization,
            config.training,
            config.gpu,
        )

        if report.status == "OOM":
            raise OOMRiskError(
                predicted_mb=report.peak_vram_mb,
                available_mb=config.gpu.total_vram_mb,
                safe_threshold_mb=config.gpu.usable_vram_mb,
                message=f"Training rejected: predicted VRAM ({report.peak_vram_mb:.1f} MB) exceeds physical GPU memory ({config.gpu.total_vram_mb} MB).",
            )

        state = JobState(
            job_id=job_id,
            status=JobStatus.RUNNING,
            start_time=time.time(),
            total_steps=total_steps,
            output_checkpoint_dir=checkpoint_dir,
        )
        self._jobs[job_id] = state
        self._stop_flags[job_id] = False

        start_time = time.time()
        best_val = float("inf")
        patience_counter = 0
        eval_interval = max(1, config.training.eval_steps)
        patience_limit = config.training.early_stopping_patience or 3
        min_delta = config.training.early_stopping_threshold

        for step in range(1, total_steps + 1):
            if self._stop_flags.get(job_id, False):
                state.status = JobStatus.CANCELLED
                state.end_time = time.time()
                return state

            sim_loss = round(2.8 * (0.97 ** step) + 0.35, 4)
            sim_lr = round(config.training.learning_rate * max(0.1, 1.0 - (step / total_steps)), 7)
            sim_vram = round(report.peak_vram_mb * (0.92 + (step / total_steps) * 0.08), 1)

            # Check if this is an evaluation step
            is_eval_step = (step % eval_interval == 0) or (step == total_steps)
            val_loss = None
            ppl = None
            is_best = False

            if is_eval_step:
                val_loss = round(sim_loss + 0.08 + (0.02 * (step / total_steps) if step > total_steps * 0.8 else 0.0), 4)
                ppl = round(math.exp(val_loss), 2)

                if (best_val - val_loss) > min_delta:
                    best_val = val_loss
                    patience_counter = 0
                    is_best = True
                    state.best_val_loss = val_loss
                    state.best_step = step
                else:
                    patience_counter += 1
                    if patience_counter >= patience_limit:
                        state.early_stopped = True

            metric = StepMetrics(
                step=step,
                epoch=round((step / total_steps) * config.training.num_train_epochs, 2),
                loss=sim_loss,
                val_loss=val_loss,
                perplexity=ppl,
                is_best_checkpoint=is_best,
                learning_rate=sim_lr,
                grad_norm=0.75,
                tokens_per_second=2400.0,
                vram_used_mb=sim_vram,
                vram_peak_mb=sim_vram,
                elapsed_seconds=round(time.time() - start_time, 2),
            )
            self.event_bus.record(metric)

            state.current_step = step
            state.current_epoch = metric.epoch
            state.latest_loss = sim_loss
            if ppl is not None:
                state.latest_perplexity = ppl
            state.peak_vram_recorded_mb = max(state.peak_vram_recorded_mb, sim_vram)

            if state.early_stopped:
                break

            if step_delay > 0:
                time.sleep(step_delay)

        state.status = JobStatus.COMPLETED
        state.end_time = time.time()

        # Save synthetic adapter checkpoint files
        chk_path = Path(checkpoint_dir)
        chk_path.mkdir(parents=True, exist_ok=True)
        adapter_cfg = {
            "base_model_name_or_path": config.model.name,
            "r": config.lora.r,
            "lora_alpha": config.lora.lora_alpha,
            "lora_dropout": config.lora.lora_dropout,
            "target_modules": config.lora.target_modules,
            "bias": config.lora.bias,
            "task_type": config.lora.task_type,
        }
        with open(chk_path / "adapter_config.json", "w", encoding="utf-8") as f:
            json.dump(adapter_cfg, f, indent=2)

        with open(chk_path / "training_summary.json", "w", encoding="utf-8") as f:
            json.dump(state.model_dump(), f, indent=2)

        return state
