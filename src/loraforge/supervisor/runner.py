import sys
import json
import time

def main():
    print("[LoRAForge Worker] Initializing training environment...", flush=True)

    try:
        import torch
        from datasets import load_dataset
        from transformers import (
            AutoModelForCausalLM,
            AutoTokenizer,
            BitsAndBytesConfig,
            TrainingArguments,
            TrainerCallback,
        )
        from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training
        from trl import SFTTrainer
    except ImportError as exc:
        print(f"[LoRAForge Error] Missing required ML framework: {{exc}}", file=sys.stderr)
        print("Install training dependencies: pip install -e .[training]", file=sys.stderr)
