"""Process supervisor managing fine-tuning lifecycle, logging, and watchdog telemetry.

Orchestrates training runs, monitors subprocess health, parses live metrics,
enforces memory tripwires, and manages LoRA adapter artifacts.
"""

from __future__ import annotations

import json
import math
import os
import subprocess
import sys
import threading
import time
from enum import Enum
from pathlib import Path
from typing import Callable, Dict, List, Optional
from pydantic import BaseModel, Field

from loraforge.core.config import FineTuningJobConfig, QuantizationType
from loraforge.core.errors import OOMRiskError, SupervisorError
